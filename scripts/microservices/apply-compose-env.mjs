#!/usr/bin/env node
/** Apply deploy/.env.compose from capexbe/.env + capex-apps/.env.local service URLs. */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '../..');
const BE_ENV = join(ROOT, 'capexbe/.env');
const FE_ENV = join(ROOT, 'capex-apps/.env.local');
const OUT = join(ROOT, 'deploy/.env.compose');

function parseEnv(text) {
  const map = new Map();
  for (const line of text.split('\n')) {
    const t = line.trim();
    if (!t || t.startsWith('#')) continue;
    const i = t.indexOf('=');
    if (i <= 0) continue;
    map.set(t.slice(0, i).trim(), t.slice(i + 1).trim());
  }
  return map;
}

if (!existsSync(BE_ENV)) {
  console.error('Missing capexbe/.env — run: make env');
  process.exit(1);
}

const be = parseEnv(readFileSync(BE_ENV, 'utf8'));
const fe = existsSync(FE_ENV) ? parseEnv(readFileSync(FE_ENV, 'utf8')) : new Map();

const keys = [
  'SUPABASE_URL',
  'SUPABASE_ANON_KEY',
  'SUPABASE_SERVICE_ROLE_KEY',
  'SUPABASE_JWT_SECRET',
  'JWT_ACCESS_SECRET',
  'REDIS_URL',
  'CORS_ORIGINS',
];

const serviceKeys = [...fe.keys()].filter((k) => k.startsWith('CAPEX_SERVICE_'));

const lines = [
  '# Auto-generated by scripts/microservices/apply-compose-env.mjs',
  '# Re-run: make compose-env',
  '',
];

for (const k of keys) {
  const v = be.get(k) ?? fe.get(k);
  if (v != null && v !== '') lines.push(`${k}=${v}`);
}

lines.push('');
lines.push('# BFF leaf overrides (host ports when using compose on localhost)');
for (const k of serviceKeys.sort()) {
  lines.push(`${k}=${fe.get(k)}`);
}

if (!lines.some((l) => l.startsWith('CORS_ORIGINS='))) {
  lines.splice(3, 0, 'CORS_ORIGINS=http://localhost:3000');
}
if (!lines.some((l) => l.startsWith('REDIS_URL='))) {
  lines.splice(3, 0, 'REDIS_URL=redis://redis:6379');
}

writeFileSync(OUT, `${lines.join('\n')}\n`);
console.log(`OK  wrote ${OUT} (${keys.filter((k) => be.get(k) || fe.get(k)).length} secrets + ${serviceKeys.length} service URLs)`);
